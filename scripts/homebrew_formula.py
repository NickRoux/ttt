"""Generate the tap formula using the checksums of published release archives."""

import argparse
from pathlib import Path
import re


PLATFORMS = (("darwin", "arm64"), ("darwin", "amd64"), ("linux", "arm64"), ("linux", "amd64"))


def generate(version, checksums):
    if not re.fullmatch(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", version):
        raise ValueError("version must be a stable semantic version such as 0.1.0")

    hashes = {}
    for line in checksums.splitlines():
        if not line.strip():
            continue
        match = re.fullmatch(r"([0-9a-f]{64}) [ *](\S+)", line)
        if not match:
            raise ValueError("invalid checksum line")
        digest, filename = match.groups()
        if filename in hashes:
            raise ValueError(f"duplicate checksum for {filename}")
        hashes[filename] = digest

    lines = [
        "# Generated by ttt's release workflow. Update from a versioned release asset.",
        "class Ttt < Formula",
        '  desc "Terminal transliteration editor with live typing and language plugins"',
        '  homepage "https://github.com/NickRoux/ttt"',
        f'  version "{version}"',
    ]
    for system, homebrew_os in (("darwin", "macos"), ("linux", "linux")):
        lines += ["", f"  on_{homebrew_os} do"]
        for arch, homebrew_arch in (("arm64", "arm"), ("amd64", "intel")):
            filename = f"ttt_{version}_{system}_{arch}.tar.gz"
            if filename not in hashes:
                raise ValueError(f"missing checksum for {filename}")
            lines += [
                f"    on_{homebrew_arch} do",
                f'      url "https://github.com/NickRoux/ttt/releases/download/v{version}/{filename}"',
                f'      sha256 "{hashes[filename]}"',
                "    end",
            ]
            if homebrew_arch == "arm":
                lines.append("")
        lines.append("  end")
    lines += [
        "",
        "  def install",
        '    bin.install "ttt"',
        '    (pkgshare/"examples").install "examples/el.json"',
        "  end",
        "",
        "  test do",
        '    assert_match version.to_s, shell_output("#{bin}/ttt --version")',
        '    assert_equal "Привет, мир!\\n", shell_output("#{bin}/ttt \'Privet, mir!\'")',
        "  end",
        "end",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True)
    parser.add_argument("--checksums", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        formula = generate(args.version, args.checksums.read_text(encoding="utf-8"))
    except ValueError as error:
        parser.error(str(error))
    args.output.write_text(formula, encoding="utf-8")


if __name__ == "__main__":
    main()
